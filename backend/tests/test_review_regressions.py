def test_invalid_requests_are_rejected_before_any_write(payload: dict[str, Any]) -> None:
    with TestClient(create_app(), base_url="http://localhost") as client:
        path = "/api/reviews/grouping" if "action" in payload else "/api/reports"
        import json

        response = client.post(
            path, content=json.dumps(payload), headers={"Content-Type": "application/json"}
        )
        assert response.status_code == 422, response.text
        assert not client.get("/api/reports").json()


def test_local_api_rejects_cross_site_writes_and_dns_rebinding() -> None:
    with TestClient(create_app(), base_url="http://localhost") as client:
        body = {"text": "Synthetic report", "idempotency_key": "test"}
        for headers in (
            {"Origin": "https://attacker.example"},
            {"Origin": "null"},
            {"Origin": "http://[invalid"},
            {"Sec-Fetch-Site": "cross-site"},
        ):
            assert client.post("/api/reports", json=body, headers=headers).status_code == 403
        assert client.get("/api/snapshot", headers={"Host": "attacker.example"}).status_code == 400
        for host in ("[bad", "localhost:bad", "user@localhost", "localhost:0"):
            assert client.get("/api/health", headers={"Host": host}).status_code == 400
        assert client.post("/api/reports", content="{}").status_code == 415
        assert not client.get("/api/reports").json()
        response = client.post(
            "/api/reports", json=body, headers={"Origin": "http://127.0.0.1:3000"}
        )
        assert response.status_code == 201
        assert response.headers["Cache-Control"] == "no-store"


